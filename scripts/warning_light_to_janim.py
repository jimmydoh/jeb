# =========================================================================
# 2. JANIM COMPILER (Do not modify)
# =========================================================================

def export_to_janim(filepath, frame_data, timings):
    frame_count = len(timings)
    output_dir = os.path.dirname(filepath)
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)

    with open(filepath, 'wb') as f:
        f.write(b'JANM')
        f.write(bytes([frame_count]))

        for i in range(frame_count):
            duration_ms = timings[i]
            f.write(duration_ms.to_bytes(2, byteorder='little', signed=False))
            start_idx = i * 256
            end_idx = start_idx + 256
            f.write(frame_data[start_idx:end_idx])

    print(f"✅ Successfully generated: {filepath}")
    print(f"   Frames: {frame_count}")
    print(f"   Timings (ms): {timings}")

if __name__ == "__main__":
    output_filename = "red_alert.janim"
    print(f"Compiling {output_filename}...")
    export_to_janim(output_filename, ANIMATION_DATA, TIMING_DATA)
